"""Measurement 8's outage timeline as a self-contained SVG (D-122).

Why it exists: PLAN.md's measurement 8 is a success rate per second with fallback on and off,
and the breaker's state changes, around a fixed outage window. The owner asked for it as a
committed chart generated by a committed script from the committed raw output.

Key design choices:

- Plain SVG text from the standard library (no matplotlib: M18 allows no dependency). No script
  and no external reference, so it renders the same on GitHub and offline; hovering a line or a
  breaker tick shows a native `<title>`.
- One y axis, success rate 0 to 100%; one line per run; fallback-on runs share one color and
  fallback-off runs another (categorical slots 1 and 2 of the dataviz skill's validated reference
  palette, on its light surface), with a legend and a direct label per variant.
- A second with no request breaks the line instead of joining across it.
- The breaker gets its own lane per run under the plot: open and half-open as bands, every
  change as a tick, so changes a fraction of a second apart never stack labels.
- Deterministic: numbers are formatted to two decimals and nothing depends on time or order of
  dictionaries, so the same input gives the same bytes.
"""

from collections.abc import Sequence
from dataclasses import dataclass
from xml.sax.saxutils import escape

from lgwload.measures import Second

SURFACE = "#fcfcfb"
TEXT = "#0b0b0b"
TEXT_SECONDARY = "#52514e"
GRID = "#e4e3df"
WINDOW_FILL = "#f0efec"
COLORS = {"on": "#2a78d6", "off": "#eb6834"}
BAND = {"open": "#52514e", "half_open": "#a9a8a2"}

WIDTH = 960
LEFT = 150
RIGHT = 24
TOP = 70
PLOT_HEIGHT = 260
LANE_HEIGHT = 12
LANE_GAP = 6


@dataclass(frozen=True)
class OutageRun:
    label: str
    variant: str
    seconds: Sequence[Second]
    breaker: Sequence[tuple[float, str]]


def _attr(value: str) -> str:
    return escape(value, {'"': "&quot;"})


def _n(value: float) -> str:
    return f"{value:.2f}"


def _segments(seconds: Sequence[Second]) -> list[list[Second]]:
    segments: list[list[Second]] = []
    current: list[Second] = []
    for second in seconds:
        if second.sent == 0:
            if current:
                segments.append(current)
            current = []
        else:
            current.append(second)
    if current:
        segments.append(current)
    return segments


def outage_svg(runs: Sequence[OutageRun], window_start_s: float, window_length_s: float) -> str:
    if not runs:
        raise ValueError("no runs to chart")
    if not window_start_s >= 0:
        raise ValueError("window_start_s must be >= 0")
    if not window_length_s > 0:
        raise ValueError("window_length_s must be > 0")
    for run in runs:
        if run.variant not in COLORS:
            raise ValueError("variant must be 'on' or 'off'")

    span = max(
        [window_start_s + window_length_s]
        + [len(run.seconds) for run in runs]
        + [time for run in runs for time, _ in run.breaker]
    )
    plot_width = WIDTH - LEFT - RIGHT
    bottom = TOP + PLOT_HEIGHT

    def x(seconds: float) -> float:
        return LEFT + seconds / span * plot_width

    def y(rate: float) -> float:
        return bottom - rate * PLOT_HEIGHT

    # Room for the tick labels (bottom + 18), the axis title (bottom + 36) and the lanes' caption.
    lanes_top = bottom + 72
    height = lanes_top + len(runs) * (LANE_HEIGHT + LANE_GAP) + 40
    out: list[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" '
        f'viewBox="0 0 {WIDTH} {height}" font-family="system-ui, sans-serif" font-size="12">',
        f'<rect x="0" y="0" width="{WIDTH}" height="{height}" fill="{SURFACE}"/>',
        f'<text x="{LEFT}" y="24" font-size="15" font-weight="600" fill="{TEXT}">'
        "Success rate per second during a 100% outage of one provider</text>",
    ]
    # Legend, above the plot.
    legend_x = LEFT
    for variant, name in (("on", "fallback on"), ("off", "fallback off")):
        out.append(
            f'<line x1="{legend_x}" y1="44" x2="{legend_x + 22}" y2="44" '
            f'stroke="{COLORS[variant]}" stroke-width="2"/>'
        )
        out.append(f'<text x="{legend_x + 28}" y="48" fill="{TEXT_SECONDARY}">{name}</text>')
        legend_x += 130
    out.append(
        f'<rect x="{legend_x}" y="37" width="22" height="14" fill="{WINDOW_FILL}" stroke="{GRID}"/>'
    )
    out.append(
        f'<text x="{legend_x + 28}" y="48" fill="{TEXT_SECONDARY}">fault window '
        f"({_n(window_start_s)} s + {_n(window_length_s)} s)</text>"
    )

    out.append(
        f'<rect data-role="window" x="{_n(x(window_start_s))}" y="{TOP}" '
        f'width="{_n(x(window_start_s + window_length_s) - x(window_start_s))}" '
        f'height="{PLOT_HEIGHT}" fill="{WINDOW_FILL}"/>'
    )
    for tick in (0.0, 0.25, 0.5, 0.75, 1.0):
        out.append(
            f'<line x1="{LEFT}" y1="{_n(y(tick))}" x2="{WIDTH - RIGHT}" y2="{_n(y(tick))}" '
            f'stroke="{GRID}" stroke-width="1"/>'
        )
        out.append(
            f'<text x="{LEFT - 8}" y="{_n(y(tick) + 4)}" text-anchor="end" '
            f'fill="{TEXT_SECONDARY}">{int(tick * 100)}%</text>'
        )
    step = 30 if span > 120 else 10
    tick_s = 0
    while tick_s <= span:
        out.append(
            f'<text x="{_n(x(tick_s))}" y="{bottom + 18}" text-anchor="middle" '
            f'fill="{TEXT_SECONDARY}">{tick_s}</text>'
        )
        tick_s += step
    out.append(
        f'<text x="{_n(LEFT + plot_width / 2)}" y="{bottom + 36}" text-anchor="middle" '
        f'fill="{TEXT_SECONDARY}">seconds since the run\'s first request</text>'
    )

    for run in runs:
        color = COLORS[run.variant]
        label = _attr(run.label)
        for segment in _segments(run.seconds):
            points = " ".join(
                f"{_n(x(s.second + 0.5))},{_n(y(s.succeeded / s.sent))}" for s in segment
            )
            out.append(
                f'<polyline data-run="{label}" data-variant="{run.variant}" points="{points}" '
                f'fill="none" stroke="{color}" stroke-width="2" stroke-opacity="0.8">'
                f"<title>{escape(run.label)}</title></polyline>"
            )
    # Direct labels in the middle of the window, where the variants part; at the run's end both
    # are usually back at 100% and the two labels would overlap.
    middle_s = int(window_start_s + window_length_s / 2)
    for variant, name in (("on", "fallback on"), ("off", "fallback off")):
        chosen = [run for run in runs if run.variant == variant and run.seconds]
        if chosen:
            at = next((s for s in chosen[0].seconds if s.second == middle_s), None)
            if at is None or at.sent == 0:
                at, at_x = chosen[0].seconds[-1], x(len(chosen[0].seconds)) - 4
                anchor = "end"
            else:
                at_x, anchor = x(middle_s + 0.5), "middle"
            rate = at.succeeded / at.sent if at.sent else 0.0
            out.append(
                f'<text x="{_n(at_x)}" y="{_n(y(rate) - 6)}" '
                f'text-anchor="{anchor}" fill="{TEXT}">{name}</text>'
            )

    out.append(
        f'<text x="{LEFT}" y="{lanes_top - 10}" fill="{TEXT}">Breaker state per run: '
        f"open (dark band), half-open (light band), closed (no band)</text>"
    )
    for index, run in enumerate(runs):
        top = lanes_top + index * (LANE_HEIGHT + LANE_GAP)
        middle = top + LANE_HEIGHT / 2
        out.append(
            f'<text x="{LEFT - 8}" y="{_n(middle + 4)}" text-anchor="end" '
            f'fill="{TEXT_SECONDARY}">{escape(run.label)}</text>'
        )
        out.append(
            f'<line x1="{LEFT}" y1="{_n(middle)}" x2="{WIDTH - RIGHT}" y2="{_n(middle)}" '
            f'stroke="{GRID}" stroke-width="1"/>'
        )
        changes = sorted(run.breaker, key=lambda change: change[0])
        for position, (time, state) in enumerate(changes):
            end = changes[position + 1][0] if position + 1 < len(changes) else span
            if state in BAND and end > time:
                out.append(
                    f'<rect x="{_n(x(time))}" y="{top}" width="{_n(x(end) - x(time))}" '
                    f'height="{LANE_HEIGHT}" fill="{BAND[state]}"/>'
                )
        for time, state in run.breaker:
            out.append(
                f'<g data-role="breaker" data-run="{_attr(run.label)}" data-to="{_attr(state)}">'
                f'<line x1="{_n(x(time))}" y1="{top - 2}" x2="{_n(x(time))}" '
                f'y2="{top + LANE_HEIGHT + 2}" stroke="{COLORS[run.variant]}" stroke-width="2"/>'
                f"<title>{escape(run.label)}: {escape(state)} at {_n(time)} s</title></g>"
            )
    out.append("</svg>")
    return "\n".join(out) + "\n"
