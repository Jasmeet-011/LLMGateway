"""Tests for `lgwload.chart`, measurement 8's outage timeline as an SVG (M18, D-122).

D-122: `outage_svg(runs, window_start_s, window_length_s)` returns a self-contained SVG (no script,
no external reference) plotting each run's success rate per second against seconds since the run's
first request, with a gap where nothing was sent, fallback-on runs in one color and fallback-off
runs in another, the fault window shaded, and each breaker state change as a marker labeled with
its new state; the same input gives the same bytes. The SVG is plain and checked on structure, not
on how it looks. The structural contract these tests rely on (the builder's brief):

- exactly one `<rect data-role="window">`;
- per run, one or more `<polyline data-run=LABEL data-variant=on|off stroke=...>`; a second with
  `sent == 0` breaks the line, so a run with one internal empty second has two polylines;
- per breaker entry, one `<g data-role="breaker" data-run=LABEL data-to=STATE>`;
- labels are XML-escaped.

Inferred from "success rate per second against seconds since the first request": a polyline has one
point per non-empty second, x grows with the second, and (SVG's y axis points down) a higher success
rate has a smaller y.

Written from the spec, before `loadtest/lgwload/chart.py` exists.
"""

import re
import xml.etree.ElementTree as ET
from collections.abc import Sequence

import pytest
from lgwload.chart import OutageRun, outage_svg
from lgwload.measures import Second

SVG_NS = "http://www.w3.org/2000/svg"


def secs(*pairs: tuple[int, int]) -> list[Second]:
    """Seconds 0, 1, 2, ... from (sent, succeeded) pairs."""
    return [Second(second=i, sent=sent, succeeded=ok) for i, (sent, ok) in enumerate(pairs)]


FULL = secs((50, 50), (50, 50), (50, 40), (50, 25), (50, 50))


def run(
    label: str = "on-1",
    variant: str = "on",
    seconds: Sequence[Second] | None = None,
    breaker: Sequence[tuple[float, str]] = (),
) -> OutageRun:
    return OutageRun(
        label=label,
        variant=variant,
        seconds=FULL if seconds is None else seconds,
        breaker=breaker,
    )


def render(runs: Sequence[OutageRun], start: float = 2.0, length: float = 2.0) -> str:
    return outage_svg(runs, start, length)


def parse(svg: str) -> ET.Element:
    # The SVG is generated by the code under test from test data; there is no untrusted input.
    return ET.fromstring(svg)  # noqa: S314


def local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def elements(svg: str, name: str) -> list[ET.Element]:
    root = parse(svg)
    return [element for element in root.iter() if local(element.tag) == name]


def polylines_of(svg: str, label: str) -> list[ET.Element]:
    return [e for e in elements(svg, "polyline") if e.get("data-run") == label]


def points_of(polyline: ET.Element) -> list[tuple[float, float]]:
    numbers = [
        float(n)
        for n in re.findall(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", polyline.get("points", ""))
    ]
    assert len(numbers) % 2 == 0, polyline.get("points")
    return list(zip(numbers[0::2], numbers[1::2], strict=True))


# --- a document that is safe to open -------------------------------------------------------


def test_the_output_is_an_svg_document_with_the_svg_namespace() -> None:
    svg = render([run()])
    assert svg.lstrip().startswith(("<svg", "<?xml"))
    assert 'xmlns="http://www.w3.org/2000/svg"' in svg
    root = parse(svg)
    assert root.tag == f"{{{SVG_NS}}}svg"


def test_the_output_has_no_script_no_href_and_no_external_address() -> None:
    svg = render(
        [run("on-1", "on", breaker=[(2.5, "open")]), run("off-1", "off", breaker=[(3.0, "open")])]
    )
    lowered = svg.lower()
    assert "<script" not in lowered
    assert "href" not in lowered
    assert "javascript:" not in lowered
    assert "onload" not in lowered
    without_namespace = svg.replace('xmlns="http://www.w3.org/2000/svg"', "")
    assert "http://" not in without_namespace
    assert "https://" not in without_namespace
    for element in parse(svg).iter():
        for name, value in element.attrib.items():
            assert not name.lower().endswith("href"), name
            assert "http://" not in value
            assert "https://" not in value


def test_the_output_is_the_same_string_for_the_same_input_twice() -> None:
    first = render([run("on-1", "on", breaker=[(2.0, "open")]), run("off-1", "off")], 2.0, 2.0)
    second = render([run("on-1", "on", breaker=[(2.0, "open")]), run("off-1", "off")], 2.0, 2.0)
    assert first == second
    assert render([run()]) == render([run()])


# --- the fault window ----------------------------------------------------------------------


def test_there_is_exactly_one_window_rectangle_however_many_runs() -> None:
    svg = render([run("a", "on"), run("b", "off"), run("c", "on")])
    windows = [e for e in elements(svg, "rect") if e.get("data-role") == "window"]
    assert len(windows) == 1


def test_the_window_rectangle_follows_the_window_arguments() -> None:
    runs = [run()]
    assert render(runs, 2.0, 2.0) != render(runs, 1.0, 2.0)
    assert render(runs, 2.0, 2.0) != render(runs, 2.0, 1.0)


def test_a_window_that_starts_at_zero_is_allowed() -> None:
    assert "<svg" in render([run()], 0.0, 1.0)


# --- the success-rate lines ----------------------------------------------------------------


def test_a_run_with_no_empty_second_is_one_polyline_with_its_label_and_variant() -> None:
    svg = render([run("on-1", "on")])
    lines = polylines_of(svg, "on-1")
    assert len(lines) == 1
    assert lines[0].get("data-variant") == "on"
    assert len(points_of(lines[0])) == len(FULL)


def test_a_run_with_one_internal_empty_second_is_two_polylines() -> None:
    seconds = secs((50, 50), (50, 45), (0, 0), (50, 30), (50, 50))
    lines = polylines_of(render([run("off-1", "off", seconds)]), "off-1")
    assert len(lines) == 2
    assert sorted(len(points_of(line)) for line in lines) == [2, 2]


def test_a_run_with_two_internal_empty_seconds_in_different_places_is_three_polylines() -> None:
    seconds = secs((5, 5), (5, 4), (0, 0), (5, 5), (5, 3), (0, 0), (5, 5), (5, 5))
    assert len(polylines_of(render([run("a", "on", seconds)]), "a")) == 3


def test_two_empty_seconds_in_a_row_still_make_only_one_gap() -> None:
    seconds = secs((5, 5), (5, 4), (0, 0), (0, 0), (5, 5), (5, 3))
    assert len(polylines_of(render([run("a", "on", seconds)]), "a")) == 2


def test_a_run_that_begins_with_an_empty_second_has_no_line_before_its_first_request() -> None:
    seconds = secs((0, 0), (5, 5), (5, 4), (5, 5))
    lines = polylines_of(render([run("a", "on", seconds)]), "a")
    assert len(lines) == 1
    assert len(points_of(lines[0])) == 3


def test_every_run_gets_its_own_polylines_and_the_label_selects_them() -> None:
    gapped = secs((5, 5), (5, 5), (0, 0), (5, 5), (5, 5))
    svg = render([run("one", "on"), run("two", "off", gapped), run("three", "on")])
    assert len(polylines_of(svg, "one")) == 1
    assert len(polylines_of(svg, "two")) == 2
    assert len(polylines_of(svg, "three")) == 1
    assert len(elements(svg, "polyline")) == 4


def test_the_line_has_one_point_per_second_with_x_rising_and_y_falling_as_the_rate_rises() -> None:
    seconds = secs((10, 0), (10, 5), (10, 10))
    [line] = polylines_of(render([run("a", "on", seconds)]), "a")
    points = points_of(line)
    assert len(points) == 3
    xs = [x for x, _ in points]
    ys = [y for _, y in points]
    assert xs == sorted(xs)
    assert len(set(xs)) == 3
    # SVG's y axis points down: success rate 0, 0.5, 1 gives y falling.
    assert ys[0] > ys[1] > ys[2]


def test_the_same_success_rate_gives_the_same_height_in_any_run() -> None:
    seconds = secs((10, 5), (10, 5))
    other = secs((40, 20), (40, 20))
    svg = render([run("a", "on", seconds), run("b", "off", other)])
    [line_a] = polylines_of(svg, "a")
    [line_b] = polylines_of(svg, "b")
    assert [y for _, y in points_of(line_a)] == [y for _, y in points_of(line_b)]


def test_the_variants_are_drawn_in_two_colors_one_per_variant() -> None:
    svg = render([run("on-1", "on"), run("off-1", "off"), run("on-2", "on"), run("off-2", "off")])
    strokes = {
        label: {e.get("stroke") for e in polylines_of(svg, label)}
        for label in ("on-1", "off-1", "on-2", "off-2")
    }
    assert strokes["on-1"] == strokes["on-2"]
    assert strokes["off-1"] == strokes["off-2"]
    assert strokes["on-1"] != strokes["off-1"]
    for colors in strokes.values():
        assert len(colors) == 1
        assert None not in colors


def test_the_color_of_a_variant_does_not_depend_on_which_runs_are_present() -> None:
    both = render([run("on-1", "on"), run("off-1", "off")])
    only_on = render([run("on-1", "on")])
    assert polylines_of(both, "on-1")[0].get("stroke") == polylines_of(only_on, "on-1")[0].get(
        "stroke"
    )


def test_data_variant_says_on_or_off_for_each_polyline() -> None:
    svg = render([run("on-1", "on"), run("off-1", "off")])
    assert {e.get("data-variant") for e in polylines_of(svg, "on-1")} == {"on"}
    assert {e.get("data-variant") for e in polylines_of(svg, "off-1")} == {"off"}


# --- breaker markers -----------------------------------------------------------------------


def breakers_of(svg: str) -> list[ET.Element]:
    return [e for e in elements(svg, "g") if e.get("data-role") == "breaker"]


def test_each_breaker_entry_is_one_marker_with_its_run_and_new_state() -> None:
    runs = [
        run("on-1", "on", breaker=[(2.1, "open"), (32.5, "half_open"), (33.0, "closed")]),
        run("off-1", "off", breaker=[(2.4, "open")]),
        run("on-2", "on"),
    ]
    markers = breakers_of(render(runs))
    seen = sorted((m.get("data-run"), m.get("data-to")) for m in markers)
    assert seen == [
        ("off-1", "open"),
        ("on-1", "closed"),
        ("on-1", "half_open"),
        ("on-1", "open"),
    ]


def test_a_run_with_no_breaker_entries_has_no_markers() -> None:
    assert breakers_of(render([run("on-1", "on"), run("off-1", "off")])) == []


def test_repeated_states_in_one_run_are_separate_markers() -> None:
    runs = [run("on-1", "on", breaker=[(2.0, "open"), (4.0, "open")])]
    assert len(breakers_of(render(runs))) == 2


def test_marker_positions_follow_the_time_of_the_entry() -> None:
    early = render([run("on-1", "on", breaker=[(1.0, "open")])])
    late = render([run("on-1", "on", breaker=[(3.0, "open")])])
    assert early != late


# --- escaping ------------------------------------------------------------------------------

AWKWARD = "a<b&\"c'>d"


def test_a_label_with_markup_characters_survives_as_an_attribute_value() -> None:
    svg = render([run(AWKWARD, "on", breaker=[(2.0, "open")]), run("plain", "off")])
    root = parse(svg)
    assert [e.get("data-run") for e in root.iter() if local(e.tag) == "polyline"].count(
        AWKWARD
    ) == 1
    assert len([m for m in breakers_of(svg) if m.get("data-run") == AWKWARD]) == 1
    assert "<b&" not in svg


def test_a_label_written_into_the_document_cannot_open_an_element() -> None:
    label = '"/><script>alert(1)</script><x a="'
    svg = render([run(label, "on", breaker=[(2.0, "open")])])
    assert "<script" not in svg.lower()
    assert [e.get("data-run") for e in elements(svg, "polyline")] == [label]


# --- errors --------------------------------------------------------------------------------


def test_no_runs_raises() -> None:
    with pytest.raises(ValueError):
        outage_svg([], 2.0, 2.0)


@pytest.mark.parametrize("length", [0.0, -1.0, -0.001])
def test_a_window_length_that_is_not_positive_raises(length: float) -> None:
    with pytest.raises(ValueError):
        outage_svg([run()], 2.0, length)


@pytest.mark.parametrize("start", [-0.001, -1.0, -60.0])
def test_a_negative_window_start_raises(start: float) -> None:
    with pytest.raises(ValueError):
        outage_svg([run()], start, 2.0)


@pytest.mark.parametrize("variant", ["maybe", "ON", "Off", "", "fallback"])
def test_a_variant_other_than_on_or_off_raises(variant: str) -> None:
    with pytest.raises(ValueError):
        outage_svg([run("a", variant)], 2.0, 2.0)


def test_one_bad_variant_among_good_runs_raises() -> None:
    with pytest.raises(ValueError):
        outage_svg([run("a", "on"), run("b", "sideways")], 2.0, 2.0)
